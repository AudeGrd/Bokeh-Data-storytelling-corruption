def load_data(path=DATA_PATH):
    """Read the master dataset, check its columns, rename them and derive corruption_score = PCI x 100."""
    data = pd.read_csv(path)
    missing = REQUIRED_COLUMNS - set(data.columns)
    if missing:
        raise ValueError(
            f"Missing columns {sorted(missing)} in {path}. "
            "Re-generate the file with notebooks/2_create_dataset.ipynb."
        )
    data = data.rename(columns=COLUMN_NAMES)
    data["corruption_score"] = data.pop("pci") * 100  # PCI: 0-1, 1 = corrupt, so just rescale it
    return data


def build_year_frame(data, year):
    """One row per country for the chosen year, with every measure oriented 'higher = more corrupt'.

    Adds perception_score (100 - CPI), regime_median and deviation
    (corruption score minus the median of the country's own regime). Rows are ordered by regime, then country."""
    frame = data[data["year"] == year].dropna(subset=["cpi", "corruption_score", "regime"])
    frame = frame[frame["regime"].isin(REGIMES)].copy()
    frame["regime"] = pd.Categorical(frame["regime"], categories=REGIMES, ordered=True)
    frame = frame.sort_values(["regime", "country"]).reset_index(drop=True)
    frame["regime"] = frame["regime"].astype(str)
    frame["region"] = frame["region"].fillna("")

    frame["perception_score"] = 100 - frame["cpi"]  # CPI: 100 = clean, so flip it
    frame["regime_median"] = frame.groupby("regime")["corruption_score"].transform("median")
    frame["deviation"] = frame["corruption_score"] - frame["regime_median"]
    return frame


def marker_style_columns(regimes, color_blind, base_size):
    """Marker shape, outline and size of every point (slides 2, 3 and 4).
    Default: same circle for everyone (colour only).
    Colour-blind mode: one shape per regime, a dark and thicker outline, and slightly bigger markers."""
    regimes = list(regimes)
    n = len(regimes)
    if color_blind:
        return {
            "marker_shape": [REGIME_SHAPES[r] for r in regimes],
            "outline_color": ["#111111"] * n,  # dark edge keeps overlapping points apart
            "outline_width": [1.8] * n,
            "marker_size": [base_size + 2] * n,
        }
    return {
        "marker_shape": ["circle"] * n,
        "outline_color": ["white"] * n,
        "outline_width": [1] * n,
        "marker_size": [base_size] * n,
    }


