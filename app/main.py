    def create_slide_4_wealth(self):
        """Slide 4: corruption score against GDP per capita (log scale), one panel per regime.
        The y label is shown only on the leftmost panels (index 0 and 2); all four panels share
        min_border_left, so the plot areas line up perfectly."""
        frame = self.latest_frame.dropna(subset=["gdp_per_capita"])
        gdp_min = frame["gdp_per_capita"].min() * 0.8
        gdp_max = frame["gdp_per_capita"].max() * 1.3
        log_gdp_min, log_gdp_max = np.log10(gdp_min), np.log10(gdp_max)
        x_range, y_range = Range1d(gdp_min, gdp_max), Range1d(0, 100)  # shared by the four panels
        stats = self.wealth_stats

        panels = []
        panel_width = FRAME_WIDTH // 2  # two panels per row = FRAME_WIDTH
        for i, (regime, color) in enumerate(REGIME_COLOR_BY_NAME.items()):
            in_regime = frame[frame["regime"] == regime]
            rank_corr = stats[regime]["rank_corr"]
            corr_text = f"rank correlation {rank_corr:+.2f}" if pd.notna(rank_corr) else "too few countries"

            panel = self._figure(
                width=panel_width, height=255, x_axis_type="log", x_range=x_range, y_range=y_range,
                title=f"{regime}: {len(in_regime)} countries, {corr_text}",
                x_axis_label="GDP per capita (log scale, $)",
                y_axis_label=CORRUPTION_AXIS_LABEL_SHORT if i % 2 == 0 else None,  # left column only
                min_border_left=65,  # same left margin on every panel, with or without the y label
            )
            if len(in_regime) >= 8:  # straight-line trend, only if there are enough countries
                slope, intercept = np.polyfit(np.log10(in_regime["gdp_per_capita"]),
                                              in_regime["corruption_score"], 1)
                trend_x = np.logspace(np.log10(in_regime["gdp_per_capita"].min()),
                                      np.log10(in_regime["gdp_per_capita"].max()), 30)
                panel.line(trend_x, slope * np.log10(trend_x) + intercept,
                           color="gray", line_dash="dashed", line_width=2)

            source = self._marker_source(
                in_regime[["gdp_per_capita", "corruption_score", "country", "deviation"]].to_dict("list"),
                [regime] * len(in_regime),
                base_size=9,
            )
            dots = panel.scatter(x="gdp_per_capita", y="corruption_score", source=source,
                                 size="marker_size", marker="marker_shape", fill_color=color, fill_alpha=0.8,
                                 line_color="outline_color", line_width="outline_width")

            # Name only the selected countries (when they belong to this regime and have GDP data).
            named = in_regime[in_regime["country"].isin(SELECTED_COUNTRIES)]
            share_of_axis = (np.log10(named["gdp_per_capita"]) - log_gdp_min) / (log_gdp_max - log_gdp_min)
            near_right_edge = share_of_axis > LABEL_FLIP_SHARE
            for subset, x_offset, align in [
                (named[~near_right_edge], 6, "left"),
                (named[near_right_edge], -6, "right"),
            ]:
                if subset.empty:
                    continue
                panel.add_layout(self._label_set(
                    x="gdp_per_capita", y="corruption_score", text="country",
                    source=ColumnDataSource(
                        data=subset[["gdp_per_capita", "corruption_score", "country"]].to_dict("list")
                    ),
                    x_offset=x_offset, y_offset=4, text_align=align, text_font_size="11px",
                ))
            panel.add_tools(HoverTool(
                renderers=[dots],
                tooltips=[("Country", "@country"), ("GDP per capita", "@gdp_per_capita{0,0}"),
                          ("Corruption score", "@corruption_score{0}"),
                          ("Distance to regime median", "@deviation{+0}")],
            ))
            panel.grid.grid_line_alpha = 0.3
            panels.append(panel)

        missing_text = "; ".join(
            f"{regime}: {s['n_missing']}" for regime, s in stats.items() if s["n_missing"] > 0
        ) or "none"

        guide = self._div(
            text=f"""
            <div style="font-size: 14px; color: #1b2a41; line-height: 1.5; margin: 0 0 12px 0;">
                <b>Key takeaway:</b> Wealthier countries tend to be cleaner across every regime (dashed trend lines slope downwards), but wealth alone does not explain the outliers.
                <div style="font-size: 12px; color: #555; margin-top: 4px;">
                    Each panel compares countries within the same regime. Countries missing due to unavailable GDP data: {missing_text}.
                </div>
            </div>
            """,
            width=FRAME_WIDTH,
        )
        return column(self._heading(4), guide, row(panels[0], panels[1], width=FRAME_WIDTH),
                      row(panels[2], panels[3], width=FRAME_WIDTH), width=FRAME_WIDTH)

    def _timeseries_panel(self, country, line, bands, width, ranges, show_y_label, show_gdp_label):
        """One small chart of slide 5: corruption score (solid line, left axis) and GDP per capita (dashed line,
        right linear axis) over a background coloured by the regime of each year."""
        x_range, y_range = ranges

        # GDP axis scaled to each country (from 0 to the country maximum)
        valid_gdp = [v for v in line["gdp_per_capita"] if pd.notna(v) and v > 0]
        max_gdp = max(valid_gdp) * 1.15 if valid_gdp else 50_000
        gdp_range = Range1d(0, max_gdp)

        panel = self._figure(
            width=width,
            height=225,
            title=country,
            x_range=x_range,
            y_range=y_range,
            min_border_left=70,
            min_border_right=75,
            extra_y_ranges={"gdp": gdp_range},
        )
        if not line["year"]:
            panel.title.text = f"{country} (no corruption score data)"
            return panel

        panel.quad(
            left="left", right="right", bottom=0, top=100, source=ColumnDataSource(data=bands),
            fill_color="regime_color", fill_alpha=0.35, line_color=None, level="underlay",
        )
        line_source = ColumnDataSource(data=line)
        curve = panel.line(x="year", y="corruption_score", source=line_source, color="#222222", line_width=2.5)
        panel.line(x="year", y="gdp_per_capita", source=line_source, y_range_name="gdp",
                   color=GDP_LINE_COLOR, line_width=2.5, line_dash="dashed")

        panel.add_tools(
            HoverTool(
                renderers=[curve],
                mode="vline",
                line_policy="nearest",
                tooltips=[("Year", "@year"), ("Corruption score", "@corruption_score{0.0}"),
                          ("GDP per capita", "@gdp_per_capita{0,0}"), ("Regime", "@regime")],
            )
        )
        panel.xaxis.ticker = [1980, 2000, 2020]
        if show_y_label:
            panel.yaxis.axis_label = CORRUPTION_AXIS_LABEL_SHORT
        panel.grid.grid_line_alpha = 0.3

        panel.add_layout(
            LinearAxis(
                y_range_name="gdp",
                axis_label="GDP per capita" if show_gdp_label else None,
                ticker=AdaptiveTicker(desired_num_ticks=4),
                formatter=NumeralTickFormatter(format="$0a"),
                axis_line_color=GDP_LINE_COLOR,
                major_tick_line_color=GDP_LINE_COLOR,
                major_label_text_color=GDP_LINE_COLOR,
                axis_label_text_color=GDP_LINE_COLOR,
            ),
            "right",
        )
        return panel

